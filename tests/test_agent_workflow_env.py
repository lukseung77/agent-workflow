class FakeRunner:
    def __init__(self, fail_prefixes: tuple[tuple[str, ...], ...] = ()) -> None:
        self.commands: list[list[str]] = []
        self.fail_prefixes = fail_prefixes

    def run(self, command: list[str] | tuple[str, ...], cwd: Path) -> env.CommandResult:
        command = list(command)
        self.commands.append(command)
        if any(tuple(command[: len(prefix)]) == prefix for prefix in self.fail_prefixes):
            return env.CommandResult(1, stderr="simulated failure")
        if command[:4] == ["git", "ls-remote", "--tags", "--refs"]:
            return env.CommandResult(0, stdout="abc refs/tags/v0.1.0\ndef refs/tags/v0.2.0\nghi refs/tags/v9.0.0-rc1\n")

        if command[:2] == ["graphify", "install"] or command[:3] == ["graphify", "antigravity", "install"]:
            agent = "antigravity"
            if "--platform" in command:
                agent = command[command.index("--platform") + 1]
            paths = {
                "codex": cwd / ".codex/skills/graphify/SKILL.md",
                "claude": cwd / ".claude/skills/graphify/SKILL.md",
                "gemini": cwd / ".gemini/skills/graphify/SKILL.md",
                "antigravity": cwd / ".agents/skills/graphify/SKILL.md",
            }
            path = paths[agent]
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text("generated by fake Graphify\n", encoding="utf-8")
        if command[:2] == ["graphify", "."] or command[:2] == ["graphify", "update"]:
            graph = cwd / "graphify-out/graph.json"
            graph.parent.mkdir(parents=True, exist_ok=True)
            graph.write_text("{}\n", encoding="utf-8")
        if command[:2] == ["rtk", "init"]:
            if "antigravity" in command:
                path = cwd / ".agents/rules/antigravity-rtk-rules.md"
            else:
                path = cwd / "RTK.md"
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text("generated by fake RTK\n", encoding="utf-8")
        return env.CommandResult(0, stdout="ok")


def installed_tools(*names: str):
    available = set(names)
    return lambda name: f"/fake/{name}" if name in available else None


class AgentWorkflowEnvironmentTest(unittest.TestCase):
    def setUp(self) -> None:
        self.temp = tempfile.TemporaryDirectory()
        self.root = Path(self.temp.name)

    def tearDown(self) -> None:
        self.temp.cleanup()

    def test_clean_project_initializes_shared_adapter_graph_and_tools(self) -> None:
        runner = FakeRunner()
        report = env.initialize(
            self.root,
            "../agent-workflow",
            ["codex", "claude", "agy", "antigravity"],
            runner=runner,
            which=installed_tools("graphify", "rtk"),
        )

        self.assertTrue(report.tools["graphify"])
        self.assertTrue(report.tools["rtk"])
        self.assertTrue(report.graph_index)
        self.assertIn(env.ADAPTER_START, (self.root / "AGENTS.md").read_text(encoding="utf-8"))
        self.assertIn(["graphify", "."], runner.commands)

    def test_missing_tools_warn_and_do_not_block_initialization(self) -> None:
        report = env.initialize(
            self.root,
            "../agent-workflow",
            ["codex"],
            runner=FakeRunner(),
            which=installed_tools(),
        )

        self.assertFalse(report.tools["graphify"])
        self.assertFalse(report.tools["rtk"])
        self.assertFalse(report.graph_index)
        self.assertTrue(report.warnings)
        self.assertTrue((self.root / "AGENTS.md").exists())

    def test_verification_runs_once_without_changes_and_at_most_twice_with_changes(self) -> None:
        for tools, expected in ((('rtk',), 1), (('graphify', 'rtk'), 2)):
            with self.subTest(tools=tools):
                runner = FakeRunner()
                env.initialize(self.root, '../agent-workflow', [], runner=runner, which=installed_tools(*tools))
                self.assertEqual(runner.commands.count(['rtk', 'gain']), expected)
                if 'graphify' in tools:
                    self.assertEqual(runner.commands.count(['graphify', '--version']), expected)

    def test_newly_installed_tools_are_used_and_verified_only_at_the_end(self) -> None:
        runner = FakeRunner()

        def which(name):
            available = name in {'uv', 'cargo'}
            if name == 'graphify':
                available = ['uv', 'tool', 'install', env.GRAPHIFY_PACKAGE] in runner.commands
            if name == 'rtk':
                available = any(command[:4] == ['cargo', 'install', '--git', env.RTK_REPO] for command in runner.commands)
            return f'/fake/{name}' if available else None

        report = env.initialize(self.root, '../agent-workflow', ['codex'], install_missing=True, runner=runner, which=which)
        self.assertTrue(report.graph_index)
        self.assertTrue(report.tools['graphify'])
        self.assertTrue(report.tools['rtk'])
        self.assertEqual(runner.commands.count(['graphify', '--version']), 1)
        self.assertEqual(runner.commands.count(['rtk', 'gain']), 1)
        self.assertLess(runner.commands.index(['graphify', '.']), runner.commands.index(['graphify', '--version']))

    def test_unsupported_agent_only_receives_requested_adapter(self) -> None:
        runner = FakeRunner()
        env.initialize(
            self.root,
            "../agent-workflow",
            ["antigravity"],
            runner=runner,
            which=installed_tools("graphify", "rtk"),
        )

        commands = [" ".join(command) for command in runner.commands]
        self.assertTrue(any("graphify antigravity install" in command for command in commands))
        self.assertFalse(any("--platform codex" in command for command in commands))
        self.assertFalse(any("--platform gemini" in command for command in commands))

    def test_repeated_initialization_is_idempotent_and_uses_incremental_graph_update(self) -> None:
        runner = FakeRunner()
        kwargs = {
            "root": self.root,
            "workflow_root": "../agent-workflow",
            "agents": ["codex"],
            "runner": runner,
            "which": installed_tools("graphify", "rtk"),
        }
        env.initialize(**kwargs)
        first_content = (self.root / "AGENTS.md").read_text(encoding="utf-8")
        env.initialize(**kwargs)
        second_content = (self.root / "AGENTS.md").read_text(encoding="utf-8")

        self.assertEqual(first_content, second_content)
        self.assertEqual(second_content.count(env.ADAPTER_START), 1)
        self.assertIn(["graphify", "update", "."], runner.commands)
        self.assertEqual(sum(command[:2] == ["graphify", "install"] for command in runner.commands), 1)

    def test_partial_install_failure_is_reported_and_other_install_continues(self) -> None:
        runner = FakeRunner(fail_prefixes=(("uv", "tool", "install"),))
        report = env.initialize(
            self.root,
            "../agent-workflow",
            ["codex"],
            install_missing=True,
            runner=runner,
            which=installed_tools("uv", "cargo"),
        )

        self.assertTrue(any("Graphify installation failed" in warning for warning in report.warnings))
        self.assertTrue(any(command[:2] == ["cargo", "install"] for command in runner.commands))
        self.assertIn("RTK installation: ok", report.actions)

    def test_existing_instruction_file_is_preserved(self) -> None:
        path = self.root / "AGENTS.md"
        path.write_text("# Existing project instructions\n\nKeep this text.\n", encoding="utf-8")

        env.initialize(
            self.root,
            "../agent-workflow",
            [],
            runner=FakeRunner(),
            which=installed_tools(),
        )

        content = path.read_text(encoding="utf-8")
        self.assertIn("# Existing project instructions", content)
        self.assertIn("Keep this text.", content)
        self.assertEqual(content.count(env.ADAPTER_START), 1)

    def test_host_configuration_is_opt_in(self) -> None:
        runner = FakeRunner()
        env.initialize(
            self.root,
            "../agent-workflow",
            ["codex", "antigravity"],
            runner=runner,
            which=installed_tools("graphify", "rtk"),
        )
        self.assertFalse(any(command[:2] == ["rtk", "init"] for command in runner.commands))

        host_runner = FakeRunner()
        env.initialize(
            self.root,
            "../agent-workflow",
            ["antigravity"],
            configure_hosts=True,
            runner=host_runner,
            which=installed_tools("graphify", "rtk"),
        )
        self.assertTrue(any(command[:2] == ["rtk", "init"] for command in host_runner.commands))

    def test_doctor_reports_only_requested_agents_and_writes_nothing(self) -> None:
        report = env.doctor(self.root, ["codex"], runner=FakeRunner(), which=installed_tools("codex"))
        self.assertEqual(report.agents, {"codex": True})
        self.assertEqual(list(self.root.iterdir()), [])
        output = io.StringIO()
        with contextlib.redirect_stdout(output):
            env.print_report(report)
        self.assertIn("not checked", output.getvalue())
        self.assertIn("Shared adapter", output.getvalue())
        self.assertIn("unknown (not inspected)", output.getvalue())

    def test_cli_doctor_json_and_invalid_agent(self) -> None:
        output, errors = io.StringIO(), io.StringIO()
        with patch.object(env.shutil, "which", installed_tools()), contextlib.redirect_stdout(output):
            code = env.main(["doctor", "--root", str(self.root), "--agents", "codex", "--json"])
        self.assertEqual(code, 0)
        self.assertEqual(json.loads(output.getvalue())["agents"], {"codex": False})
        with contextlib.redirect_stderr(errors):
            code = env.main(["init", "--root", str(self.root), "--agents", "cluade"])
        self.assertEqual(code, 2)
        self.assertIn("unknown agent", errors.getvalue())
        self.assertFalse((self.root / "AGENTS.md").exists())

    def test_pipx_fallback_uses_requested_version_and_rtk_revision(self) -> None:
        runner = FakeRunner()
        env.initialize(
            self.root, "../agent-workflow", [], install_missing=True,
            runner=runner, which=installed_tools("pipx", "cargo"),
            graphify_version="1.2.3", rtk_revision="abc123",
        )
        self.assertIn(["pipx", "install", "graphifyy==1.2.3"], runner.commands)
        self.assertIn(["cargo", "install", "--git", env.RTK_REPO, "--rev", "abc123"], runner.commands)

    def test_cli_init_dispatches_install_and_version_options(self) -> None:
        with patch.object(env, "initialize", return_value=env.EnvironmentReport()) as initialize:
            with contextlib.redirect_stdout(io.StringIO()):
                code = env.main([
                    "init", "--root", str(self.root), "--agents", "gemini",
                    "--install-missing", "--configure-hosts", "--json",
                    "--graphify-version", "1.2.3", "--rtk-revision", "abc123",
                ])
        self.assertEqual(code, 0)
        self.assertEqual(initialize.call_args.args[2], ["agy"])
        self.assertTrue(initialize.call_args.kwargs["install_missing"])
        self.assertTrue(initialize.call_args.kwargs["configure_hosts"])
        self.assertEqual(initialize.call_args.kwargs["graphify_version"], "1.2.3")
        self.assertEqual(initialize.call_args.kwargs["rtk_revision"], "abc123")

    def test_registry_installs_latest_stable_tag_and_records_versions_locally(self) -> None:
        runner = FakeRunner()
        report = env.initialize(self.root, './agent-workflow-foundation', [], install_missing=True, runner=runner, which=installed_tools('cargo'))
        self.assertIn(['cargo', 'install', '--git', env.ORIGINS['rtk']['origin'], '--tag', 'v0.2.0'], runner.commands)
        self.assertFalse(any('v9.0.0-rc1' in command for command in runner.commands))
        inventory = json.loads((self.root / 'agent-workflow-local/tooling.json').read_text())
        self.assertEqual(inventory['tools']['rtk']['origin'], env.ORIGINS['rtk']['origin'])
        self.assertIsNone(inventory['tools']['rtk']['version'])

    def test_inventory_preserves_manual_plugin_verification_and_other_tools(self) -> None:
        path = self.root / 'agent-workflow-local/tooling.json'
        path.parent.mkdir()
        path.write_text(json.dumps({'custom': 'preserved', 'tools': {'ponytail': {'native_state': 'verified', 'version': 'reviewed'}, 'other': {'version': '1'}}}))
        env.initialize(self.root, './agent-workflow-foundation', [], runner=FakeRunner(), which=installed_tools('graphify', 'rtk'))
        inventory = json.loads(path.read_text())
        self.assertEqual(inventory['custom'], 'preserved')
        self.assertEqual(inventory['tools']['ponytail']['native_state'], 'verified')
        self.assertEqual(inventory['tools']['ponytail']['version'], 'reviewed')
        self.assertEqual(inventory['tools']['other']['version'], '1')
        self.assertEqual(inventory['tools']['graphify']['version'], 'ok')
        self.assertEqual(inventory['tools']['rtk']['version'], 'ok')

    def test_unresolved_stable_release_does_not_install_development_head(self) -> None:
        runner = FakeRunner(fail_prefixes=(('git', 'ls-remote'),))
        report = env.initialize(self.root, './agent-workflow-foundation', [], install_missing=True, runner=runner, which=installed_tools('cargo'))
        self.assertFalse(any(command[:2] == ['cargo', 'install'] for command in runner.commands))
        self.assertTrue(any('stable release could not be resolved' in warning for warning in report.warnings))

    def test_local_rtk_file_does_not_suppress_requested_global_configuration(self) -> None:
        (self.root / "RTK.md").write_text("Local instructions only\n", encoding="utf-8")
        runner = FakeRunner()
        env.initialize(self.root, "../agent-workflow", ["codex"], configure_hosts=True, runner=runner, which=installed_tools("rtk"))
        self.assertIn(["rtk", "init", "--global", "--codex"], runner.commands)

    def test_optional_command_exceptions_do_not_abort_other_tools(self) -> None:
        for failure in (FileNotFoundError("missing"), subprocess.TimeoutExpired("graphify", 300)):
            with self.subTest(failure=type(failure).__name__):
                runner = FakeRunner()
                original = runner.run

                def run(command, cwd):
                    if command[0] == "graphify":
                        raise failure
                    return original(command, cwd)

                runner.run = run
                report = env.initialize(self.root, "../agent-workflow", [], runner=runner, which=installed_tools("graphify", "rtk"))
                self.assertFalse(report.tools["graphify"])
                self.assertTrue(report.tools["rtk"])
                self.assertTrue(any("Graphify version check failed" in warning for warning in report.warnings))

    def test_adapter_updates_pointer_and_preserves_surrounding_content(self) -> None:
        path = self.root / "AGENTS.md"
        path.write_text("# Existing\n", encoding="utf-8")
        env.ensure_repository_adapter(self.root, "../old-workflow")
        with path.open("a", encoding="utf-8") as output:
            output.write("\nKeep this footer.\n")
        self.assertTrue(env.ensure_repository_adapter(self.root, "./agent-workflow"))
        content = path.read_text(encoding="utf-8")
        self.assertIn("# Existing\n", content)
        self.assertIn("Keep this footer.", content)
        self.assertIn("./agent-workflow/workflow/agent-tooling.md", content)
        self.assertNotIn("../old-workflow", content)
        self.assertFalse(env.ensure_repository_adapter(self.root, "./agent-workflow"))

    def test_malformed_managed_block_is_rejected_without_rewriting(self) -> None:
        path = self.root / "AGENTS.md"
        for content in (env.ADAPTER_START, env.ADAPTER_END + "\n" + env.ADAPTER_START):
            with self.subTest(content=content):
                path.write_text(content, encoding="utf-8")
                with self.assertRaises(ValueError):
                    env.ensure_repository_adapter(self.root, "../agent-workflow")
                self.assertEqual(path.read_text(encoding="utf-8"), content)
                report = env.doctor(self.root, [], runner=FakeRunner(), which=installed_tools())
                self.assertFalse(report.tools["ponytail"])
                self.assertTrue(report.warnings)


